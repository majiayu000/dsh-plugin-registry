const SIGNAL_LABELS = {
  'zh-CN': {
    repository_public: '公开仓库可访问',
    discovery_topic: '包含 dsh-plugin Topic',
    bundle_manifest: '声明有效的 dsh.bundle',
    repository_status: '仓库未归档且不是 Fork',
    passed: '通过',
    failed: '未通过',
  },
  'en-US': {
    repository_public: 'Public repository is accessible',
    discovery_topic: 'Includes the dsh-plugin topic',
    bundle_manifest: 'Declares a valid dsh.bundle',
    repository_status: 'Repository is unarchived and not a fork',
    passed: 'passed',
    failed: 'failed',
  },
}

export function buildGitHubSubmissionUrl({ registryRepository, repository, check, locale = 'zh-CN' }) {
  if (!/^[^/\s]+\/[^/\s]+$/.test(registryRepository || '')) throw new Error('registryRepository must be owner/repository')
  if (!/^[^/\s]+\/[^/\s]+$/.test(repository || '')) throw new Error('repository must be owner/repository')

  const english = locale === 'en-US'
  const labels = SIGNAL_LABELS[english ? 'en-US' : 'zh-CN']
  const signalLines = (check?.signals || []).map(item => {
    const passed = Boolean(item?.signal?.passed)
    return `- [${passed ? 'x' : ' '}] ${labels[item.signal_type] || item.signal_type} — ${passed ? labels.passed : labels.failed}`
  })
  const listing = check?.listing?.listed
    ? (english ? `Already listed via: ${check.listing.source}` : `当前已收录，来源：${check.listing.source}`)
    : (english ? 'Not currently listed' : '当前尚未收录')

  const body = english
    ? [
        '## Plugin repository',
        `https://github.com/${repository}`,
        '',
        '## Automated pre-check',
        ...signalLines,
        '',
        `Registry status: ${listing}`,
        '',
        '## Author confirmation',
        '- [ ] I own or substantially maintain this repository and am authorized to submit it.',
        '- [ ] I reviewed the listing policy and understand that manifest validation is not a security audit.',
        '',
        '## Reviewer notes',
        '<!-- Add context that helps maintainers review this plugin. -->',
        '',
        '<!-- Generated by the Harness Registry publish page. -->',
      ].join('\n')
    : [
        '## 插件仓库',
        `https://github.com/${repository}`,
        '',
        '## 自动预检',
        ...signalLines,
        '',
        `Registry 状态：${listing}`,
        '',
        '## 作者确认',
        '- [ ] 我是该仓库的所有者或主要维护者，并有权提交收录。',
        '- [ ] 我已阅读收录规范，并理解 Manifest 校验不等于安全审计。',
        '',
        '## 补充说明',
        '<!-- 请补充有助于维护者审核的信息。 -->',
        '',
        '<!-- 此内容由 Harness Registry 发布页生成。 -->',
      ].join('\n')

  const url = new URL(`https://github.com/${registryRepository}/issues/new`)
  url.searchParams.set('title', `[Plugin submission] ${repository}`)
  url.searchParams.set('labels', 'plugin-submission')
  url.searchParams.set('body', body)
  return url.toString()
}

export function submissionQueueUrl(registryRepository) {
  if (!/^[^/\s]+\/[^/\s]+$/.test(registryRepository || '')) throw new Error('registryRepository must be owner/repository')
  return `https://github.com/${registryRepository}/issues?q=is%3Aissue+label%3Aplugin-submission`
}
